<?php

declare(strict_types=1);

namespace Ultra\Signal_Postgres;

final readonly class PostgresSignalSchema
{
    public function __construct(private string $tablePrefix = 'ultra_') {}

    /**
     * @return list<string>
     */
    public function createStatements(): array
    {
        return [
            'CREATE EXTENSION IF NOT EXISTS btree_gist',
            sprintf(
                'CREATE TABLE IF NOT EXISTS %s (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    queue_name TEXT NOT NULL,
                    bucket INT NOT NULL DEFAULT 0,
                    signal_key TEXT NULL,
                    insert_xid XID8 NOT NULL DEFAULT pg_current_xact_id(),
                    visible_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
                    delivery_owner TEXT NULL,
                    delivery_until TIMESTAMPTZ NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
                )',
                $this->signalsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_claim_idx ON %s (queue_name, visible_at, id)',
                $this->signalsTable(),
                $this->signalsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_delivery_idx ON %s (delivery_until)',
                $this->signalsTable(),
                $this->signalsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_ack_idx ON %s (queue_name, bucket, id)',
                $this->signalsTable(),
                $this->signalsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_key_idx ON %s (queue_name, signal_key)',
                $this->signalsTable(),
                $this->signalsTable(),
            ),
            sprintf(
                'CREATE TABLE IF NOT EXISTS %s (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    queue_name TEXT NOT NULL,
                    bucket_range INT4RANGE NOT NULL,
                    owner TEXT NOT NULL,
                    domain_lease_ref TEXT NULL,
                    suppress_until TIMESTAMPTZ NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
                )',
                $this->suppressionsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_range_idx ON %s USING GIST (queue_name, bucket_range)',
                $this->suppressionsTable(),
                $this->suppressionsTable(),
            ),
            sprintf(
                'CREATE INDEX IF NOT EXISTS %s_until_idx ON %s (suppress_until)',
                $this->suppressionsTable(),
                $this->suppressionsTable(),
            ),
        ];
    }

    /**
     * @return list<string>
     */
    public function dropStatements(): array
    {
        return [
            sprintf('DROP TABLE IF EXISTS %s', $this->suppressionsTable()),
            sprintf('DROP TABLE IF EXISTS %s', $this->signalsTable()),
        ];
    }

    public function signalsTable(): string
    {
        return $this->tablePrefix.'signals';
    }

    public function suppressionsTable(): string
    {
        return $this->tablePrefix.'signal_suppressions';
    }
}
