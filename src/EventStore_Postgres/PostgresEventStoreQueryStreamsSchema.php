<?php

declare(strict_types=1);

namespace Ultra\EventStore_Postgres;

/**
 * Generates the PostgreSQL DDL required by `PostgresEventStoreQueryStreams`.
 */
final readonly class PostgresEventStoreQueryStreamsSchema implements PostgresEventStoreSchemaDefinition
{
    public function __construct(
        private string $tablePrefix = 'event_store_',
    ) {}

    /**
     * @return list<string>
     */
    public function createStatements(): array
    {
        return [
            sprintf(
                'CREATE TABLE %1$sevents (
                    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_type TEXT NOT NULL,
                    payload JSONB NOT NULL,
                    domain_ids JSONB NOT NULL,
                    recorded_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
                )',
                $this->tablePrefix,
            ),
            sprintf(
                'CREATE TABLE %1$sevent_query_streams (
                    event_id BIGINT NOT NULL REFERENCES %1$sevents(event_id) ON DELETE CASCADE,
                    query_stream_key TEXT NOT NULL,
                    PRIMARY KEY (event_id, query_stream_key)
                )',
                $this->tablePrefix,
            ),
            sprintf(
                'CREATE INDEX %1$sevent_query_streams_query_stream_key_idx ON %1$sevent_query_streams (query_stream_key, event_id)',
                $this->tablePrefix,
            ),
            sprintf(
                <<<'SQL'
                    CREATE FUNCTION %1$sacquire_advisory_locks(lock_ids BIGINT[], exclusive_modes BOOLEAN[]) RETURNS void AS $$
                    DECLARE
                        position INTEGER;
                    BEGIN
                        IF COALESCE(array_length(lock_ids, 1), 0) <> COALESCE(array_length(exclusive_modes, 1), 0) THEN
                            RAISE EXCEPTION 'Lock id and mode array lengths must match';
                        END IF;

                        FOR position IN 1..COALESCE(array_length(lock_ids, 1), 0)
                        LOOP
                            IF exclusive_modes[position] THEN
                                PERFORM pg_advisory_xact_lock(lock_ids[position]);
                            ELSE
                                PERFORM pg_advisory_xact_lock_shared(lock_ids[position]);
                            END IF;
                        END LOOP;
                    END;
                    $$ LANGUAGE plpgsql
                    SQL,
                $this->tablePrefix,
            ),
        ];
    }

    /**
     * @return list<string>
     */
    public function dropStatements(): array
    {
        return [
            sprintf('DROP FUNCTION IF EXISTS %sacquire_advisory_locks(BIGINT[], BOOLEAN[])', $this->tablePrefix),
            sprintf('DROP TABLE IF EXISTS %sevent_query_streams', $this->tablePrefix),
            sprintf('DROP TABLE IF EXISTS %sevents', $this->tablePrefix),
        ];
    }
}
