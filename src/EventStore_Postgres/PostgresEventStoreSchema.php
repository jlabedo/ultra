<?php

declare(strict_types=1);

namespace Ultra\EventStore_Postgres;

/**
 * Generates the PostgreSQL DDL required by `PostgresEventStore`.
 */
final readonly class PostgresEventStoreSchema
{
    public function __construct(
        private string $tablePrefix = 'event_store_',
    ) {}

    /**
     * Statements needed to create the event and query-membership tables plus the advisory-lock helper.
     *
     * @return list<string>
     */
    public function createStatements(): array
    {
        return [
            sprintf(
                'CREATE TABLE %1$sevents (
                    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_type TEXT NOT NULL,
                    payload JSONB NOT NULL,
                    domain_ids JSONB NOT NULL,
                    recorded_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
                )',
                $this->tablePrefix,
            ),
            sprintf(
                'CREATE TABLE %1$sevent_query_streams (
                    event_id BIGINT NOT NULL REFERENCES %1$sevents(event_id) ON DELETE CASCADE,
                    query_stream_key TEXT NOT NULL,
                    PRIMARY KEY (event_id, query_stream_key)
                )',
                $this->tablePrefix,
            ),
            sprintf(
                'CREATE INDEX %1$sevent_query_streams_query_stream_key_idx ON %1$sevent_query_streams (query_stream_key, event_id)',
                $this->tablePrefix,
            ),
            sprintf(
                <<<'SQL'
                    CREATE FUNCTION %1$sacquire_advisory_locks(lock_modes JSONB) RETURNS void AS $$
                    DECLARE
                        lock_entry RECORD;
                    BEGIN
                        FOR lock_entry IN
                            SELECT
                                (entry.value->>0)::BIGINT AS lock_id,
                                entry.value->>1 AS mode
                            FROM jsonb_array_elements(lock_modes) WITH ORDINALITY AS entry(value, position)
                            ORDER BY entry.position
                        LOOP
                            IF lock_entry.mode = 'exclusive' THEN
                                PERFORM pg_advisory_xact_lock(lock_entry.lock_id);
                            ELSIF lock_entry.mode = 'shared' THEN
                                PERFORM pg_advisory_xact_lock_shared(lock_entry.lock_id);
                            ELSE
                                RAISE EXCEPTION 'Unsupported advisory lock mode: %%', lock_entry.mode;
                            END IF;
                        END LOOP;
                    END;
                    $$ LANGUAGE plpgsql
                    SQL,
                $this->tablePrefix,
            ),
        ];
    }

    /**
     * Statements needed to tear down the schema created by `createStatements()`.
     *
     * @return list<string>
     */
    public function dropStatements(): array
    {
        return [
            sprintf('DROP FUNCTION IF EXISTS %sacquire_advisory_locks(JSONB)', $this->tablePrefix),
            sprintf('DROP TABLE IF EXISTS %sevent_query_streams', $this->tablePrefix),
            sprintf('DROP TABLE IF EXISTS %sevents', $this->tablePrefix),
        ];
    }
}
