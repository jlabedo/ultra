<?php

declare(strict_types=1);

namespace Ultra\Mediator_Compiler;


/**
 * Generates a compiled mediator PHP class from a resolved handler map.
 *
 * The generated class implements MediatorInterface via:
 *  - a send() method with a hardcoded match expression that delegates to a private
 *    dispatch method per message type;
 *  - one private dispatchXxx() method per message type, which inlines all AOP advice
 *    (before calls, around chain) and the handler call with its service dependencies.
 *
 * Everything is resolved lazily from a Psr\Container\ContainerInterface at runtime.
 * No reflection, no dispatch table — pure generated PHP.
 *
 * Handler map format:
 *   array<class-string, array{
 *     0: string,                  // handler service ID
 *     1: string,                  // handler method name
 *     2: list<string>,            // method-level dep service IDs (all dep types, including claimed)
 *     3: list<AdviceDescriptor>,  // (optional) ordered aspect advices
 *   }>
 *
 * Claimed dep slots (declared via MatchResult::apply(provides: [...]) in #[Around] closures)
 * are passed as extra arrow-function parameters in the $proceed lambda rather than being
 * fetched from the service locator. PHP arrow functions automatically capture outer-scope
 * variables, so nested around chains with multiple claiming aspects work without explicit
 * use clauses.
 */
final class MediatorGenerator
{
    /**
     * Generate the PHP source and write it to disk.
     *
     * @param array<class-string, array{0: string, 1: string, 2: list<string>, 3?: list<AdviceDescriptor>}> $handlers
     */
    public function generate(string $className, array $handlers, string $filePath): void
    {
        $dir = dirname($filePath);
        if (!is_dir($dir)) {
            mkdir($dir, 0o777, true);
        }

        file_put_contents($filePath, $this->buildCode($className, $handlers));
    }

    /**
     * Build the PHP source code string. Exposed for testing without filesystem I/O.
     *
     * @param array<class-string, array{0: string, 1: string, 2: list<string>, 3?: list<AdviceDescriptor>}> $handlers
     */
    public function buildCode(string $className, array $handlers): string
    {
        $matchArms = [];
        $dispatchMethods = [];

        foreach ($handlers as $messageClass => [$serviceId, $method, $depServiceIds, $advices]) {
            $dispatchName = $this->dispatchMethodName($messageClass);

            $matchArms[] = sprintf(
                '        \\%s::class => $this->%s($message, $context),',
                ltrim($messageClass, '\\'),
                $dispatchName,
            );

            $dispatchMethods[] = $this->buildDispatchMethod(
                $dispatchName,
                $serviceId,
                $method,
                $depServiceIds,
                $advices,
            );
        }

        $matchArmsCode = implode("\n", $matchArms) . "\n";
        $dispatchMethodsCode = implode("\n\n", $dispatchMethods);

        return <<<PHP
            <?php

            // This file is auto-generated by Ultra\\Mediator_Compiler\\MediatorCompilerPass. Do not edit manually.

            final class {$className} implements \\Ultra\\Mediator\\MediatorInterface
            {
                public function __construct(
                    private \\Psr\\Container\\ContainerInterface \$locator
                ) {}

                public function send(object \$message, array \$context = []): mixed
                {
                    return match (\$message::class) {
            {$matchArmsCode}            default => throw new \\Ultra\\Mediator\\Exception\\NoHandlerFound(\$message::class),
                    };
                }

            {$dispatchMethodsCode}
            }
            PHP;
    }

    /**
     * @param list<string>           $depServiceIds
     * @param list<AdviceDescriptor> $advices
     */
    private function buildDispatchMethod(
        string $dispatchName,
        string $serviceId,
        string $handlerMethod,
        array $depServiceIds,
        array $advices,
    ): string {
        $befores         = array_values(array_filter($advices, fn($a) => $a->type === AdviceType::Before));
        $arounds         = array_values(array_filter($advices, fn($a) => $a->type === AdviceType::Around));
        $afterReturnings = array_values(array_filter($advices, fn($a) => $a->type === AdviceType::AfterReturning));
        $afterThrowings  = array_values(array_filter($advices, fn($a) => $a->type === AdviceType::AfterThrowing));
        $afters          = array_values(array_filter($advices, fn($a) => $a->type === AdviceType::After));

        // Collect all dep indices claimed by parameter-providing around advices.
        // Each claimed index maps to a generated variable name $_p{depIndex}.
        // Arrow functions auto-capture outer-scope variables, so nested around
        // chains with different claiming aspects compose correctly without use clauses.
        $claimedVarNames = []; // depIndex => '$_p{depIndex}'
        foreach ($arounds as $advice) {
            foreach ($advice->claimedDepIndices as $depIdx) {
                $claimedVarNames[$depIdx] = '$_p' . $depIdx;
            }
        }

        $lines = [];

        // Before advices — sequential calls before the core expression
        foreach ($befores as $advice) {
            $beforeArgs = ['$message', '$context'];
            if ($advice->runtimeConfig !== []) {
                $beforeArgs[] = $this->exportValue($advice->runtimeConfig);
            }
            $lines[] = sprintf(
                '        $this->locator->get(%s)->%s(%s);',
                $this->exportString($advice->serviceId),
                $advice->method,
                implode(', ', $beforeArgs),
            );
        }

        // Build the core expression (handler call, optionally wrapped in around chain)
        $coreExpr = $this->buildCoreExpression(
            $serviceId, $handlerMethod, $depServiceIds, $arounds, $claimedVarNames,
        );

        // Emit the core expression, wrapped in try/catch/finally when after-type advices apply
        $needsCatch   = $afterThrowings !== [];
        $needsFinally = $afters !== [];
        $needsTry     = $needsCatch || $needsFinally;

        if (!$needsTry && $afterReturnings === []) {
            // Simple path: no after-type advices
            $lines[] = '        return ' . $coreExpr . ';';
        } elseif (!$needsTry) {
            // AfterReturning only — no try block needed
            $lines[] = '        $__result = ' . $coreExpr . ';';
            foreach ($afterReturnings as $advice) {
                $lines[] = $this->buildAfterReturningCall('        ', $advice);
            }
            $lines[] = '        return $__result;';
        } else {
            // try block — always capture the result so AfterReturning can observe it
            $lines[] = '        try {';
            $lines[] = '            $__result = ' . $coreExpr . ';';
            foreach ($afterReturnings as $advice) {
                $lines[] = $this->buildAfterReturningCall('            ', $advice);
            }
            $lines[] = '            return $__result;';
            if ($needsCatch) {
                $lines[] = '        } catch (\Throwable $__e) {';
                foreach ($afterThrowings as $advice) {
                    $lines[] = $this->buildAfterThrowingCall('            ', $advice);
                }
                $lines[] = '            throw $__e;';
            }
            if ($needsFinally) {
                $lines[] = '        } finally {';
                foreach ($afters as $advice) {
                    $lines[] = $this->buildAfterCall('            ', $advice);
                }
            }
            $lines[] = '        }';
        }

        $body = implode("\n", $lines);

        return <<<PHP
                private function {$dispatchName}(object \$message, array \$context): mixed
                {
            {$body}
                }
            PHP;
    }

    /**
     * Build the core expression: handler call, wrapped in the around chain if present.
     *
     * @param list<string>           $depServiceIds
     * @param list<AdviceDescriptor> $arounds
     * @param array<int, string>     $claimedVarNames
     */
    private function buildCoreExpression(
        string $serviceId,
        string $handlerMethod,
        array $depServiceIds,
        array $arounds,
        array $claimedVarNames,
    ): string {
        if ($arounds === []) {
            // No around advices — call handler directly with $message and all deps from locator
            $handlerArgs = ['$message'];
            foreach ($depServiceIds as $depId) {
                $handlerArgs[] = '$this->locator->get(' . $this->exportString($depId) . ')';
            }

            return sprintf(
                '$this->locator->get(%s)->%s(%s)',
                $this->exportString($serviceId),
                $handlerMethod,
                implode(', ', $handlerArgs),
            );
        }

        // Build the around chain from the inside out.
        // The innermost layer is the handler call, using $m (lambda parameter).
        // Claimed dep slots use their assigned variable names; unclaimed deps come
        // from the locator.
        $handlerArgs = ['$m'];
        foreach ($depServiceIds as $depIdx => $depId) {
            $handlerArgs[] = isset($claimedVarNames[$depIdx])
                ? $claimedVarNames[$depIdx]
                : '$this->locator->get(' . $this->exportString($depId) . ')';
        }

        $inner = sprintf(
            '$this->locator->get(%s)->%s(%s)',
            $this->exportString($serviceId),
            $handlerMethod,
            implode(', ', $handlerArgs),
        );

        // Wrap with around advices. Traverse in reverse so the highest-priority
        // advice becomes the outermost wrapper.
        foreach (array_reverse($arounds) as $i => $advice) {
            $isOutermost = ($i === count($arounds) - 1);
            $mArg = $isOutermost ? '$message' : '$m';
            $cArg = $isOutermost ? '$context' : '$c';

            // Lambda params: $m and $c, plus any dep vars this advice claims.
            // Inner lambdas auto-capture claimed vars from outer lambda scopes.
            $lambdaParams = ['$m', '$c'];
            foreach ($advice->claimedDepIndices as $depIdx) {
                $lambdaParams[] = $claimedVarNames[$depIdx];
            }

            // Aspect call args: proceed lambda, message, context, and — when the
            // advice carries a non-empty runtimeConfig — a PHP literal array.
            $aspectArgs = [
                'fn(' . implode(', ', $lambdaParams) . ') => ' . $inner,
                $mArg,
                $cArg,
            ];
            if ($advice->runtimeConfig !== []) {
                $aspectArgs[] = $this->exportValue($advice->runtimeConfig);
            }

            $inner = sprintf(
                '$this->locator->get(%s)->%s(%s)',
                $this->exportString($advice->serviceId),
                $advice->method,
                implode(', ', $aspectArgs),
            );
        }

        return $inner;
    }

    private function buildAfterReturningCall(string $indent, AdviceDescriptor $advice): string
    {
        $args = ['$message', '$context', '$__result'];
        if ($advice->runtimeConfig !== []) {
            $args[] = $this->exportValue($advice->runtimeConfig);
        }

        return sprintf(
            '%s$this->locator->get(%s)->%s(%s);',
            $indent,
            $this->exportString($advice->serviceId),
            $advice->method,
            implode(', ', $args),
        );
    }

    private function buildAfterThrowingCall(string $indent, AdviceDescriptor $advice): string
    {
        $args = ['$message', '$context', '$__e'];
        if ($advice->runtimeConfig !== []) {
            $args[] = $this->exportValue($advice->runtimeConfig);
        }

        return sprintf(
            '%s$this->locator->get(%s)->%s(%s);',
            $indent,
            $this->exportString($advice->serviceId),
            $advice->method,
            implode(', ', $args),
        );
    }

    private function buildAfterCall(string $indent, AdviceDescriptor $advice): string
    {
        $args = ['$message', '$context'];
        if ($advice->runtimeConfig !== []) {
            $args[] = $this->exportValue($advice->runtimeConfig);
        }

        return sprintf(
            '%s$this->locator->get(%s)->%s(%s);',
            $indent,
            $this->exportString($advice->serviceId),
            $advice->method,
            implode(', ', $args),
        );
    }

    /**
     * Derive a unique-enough private method name from a message FQCN.
     * Uses the short class name for readability, with a short hash to prevent
     * collisions between messages that share the same short name.
     */
    private function dispatchMethodName(string $messageClass): string
    {
        $short = substr($messageClass, strrpos($messageClass, '\\') + 1);

        return 'dispatch' . $short . '_' . substr(md5($messageClass), 0, 6);
    }

    private function exportString(string $value): string
    {
        return "'" . str_replace('\\', '\\\\', $value) . "'";
    }

    /**
     * Export a scalar or array value as a PHP literal string for code generation.
     * Supports string, int, float, bool, null, and recursively nested arrays.
     */
    private function exportValue(mixed $value): string
    {
        return match (true) {
            is_string($value) => $this->exportString($value),
            is_int($value)    => (string) $value,
            is_float($value)  => var_export($value, true),
            is_bool($value)   => $value ? 'true' : 'false',
            is_null($value)   => 'null',
            $value === []     => '[]',
            is_array($value)  => $this->exportArray($value),
            default           => throw new \LogicException(
                'Unsupported type in runtimeConfig: ' . get_debug_type($value),
            ),
        };
    }

    private function exportArray(array $array): string
    {
        $isList = array_is_list($array);
        $pairs  = [];
        foreach ($array as $k => $v) {
            $pairs[] = ($isList ? '' : $this->exportValue($k) . ' => ') . $this->exportValue($v);
        }

        return '[' . implode(', ', $pairs) . ']';
    }
}
