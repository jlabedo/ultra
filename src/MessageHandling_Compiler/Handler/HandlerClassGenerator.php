<?php

declare(strict_types=1);

namespace Ultra\MessageHandling_Compiler\Handler;

/**
 * Generates standalone handler classes that implement MessageHandlerInterface.
 *
 * Each generated class wraps a single handler method invocation with its full
 * AOP advice chain. The class receives a PSR-11 service locator for resolving
 * the handler service and its dependencies.
 *
 * This replaces the previous approach of generating private methods inside
 * the compiled router class.
 */
final class HandlerClassGenerator
{
    public function __construct(
        private readonly DispatchPlanBuilder $planBuilder = new DispatchPlanBuilder(),
        private readonly DispatchPlanRenderer $renderer = new DispatchPlanRenderer(),
    ) {}

    /**
     * Generate a handler class file and return its metadata.
     *
     * The class name is derived from a content hash of the generated code
     * (same approach as MessageRouterGenerator): build with placeholder,
     * hash, replace.
     *
     * @return array{className: string, filePath: string}
     */
    public function generate(
        string $baseName,
        HandlerDescriptor $handler,
        string $outputDir,
        ?string $wrappersFilePath = null,
    ): array {
        $placeholder = '__ULTRA_HANDLER_CLASS__';
        $code = $this->buildCode($placeholder, $handler, $wrappersFilePath);

        $hash = substr(sha1($code), 0, 8);
        $className = $baseName . '_' . $hash;
        $code = str_replace($placeholder, $className, $code);

        $filePath = rtrim($outputDir, '/') . '/' . $className . '.php';
        $dir = dirname($filePath);
        if (! is_dir($dir)) {
            mkdir($dir, 0o777, true);
        }

        file_put_contents($filePath, $code);

        return ['className' => $className, 'filePath' => $filePath];
    }

    /**
     * Build the PHP source code string for a handler class.
     */
    public function buildCode(string $className, HandlerDescriptor $handler, ?string $wrappersFilePath = null): string
    {
        $plan = $this->planBuilder->build(
            $handler->serviceId,
            $handler->method->getName(),
            $handler->depServiceIds,
            $handler->advices,
            $handler->returnsVoid,
        );

        $body = $this->renderer->renderBody($plan);

        $requireLine = null !== $wrappersFilePath
            ? "\nrequire_once " . var_export($wrappersFilePath, true) . ";\n"
            : '';

        return <<<PHP
            <?php

            // This file is auto-generated by Ultra\\MessageHandling_Compiler\\MessageRouterCompilerPass. Do not edit manually.
            {$requireLine}
            final class {$className} implements \\Ultra\\MessageHandling\\Handler\\MessageHandlerInterface
            {
                public function __construct(
                    private \\Psr\\Container\\ContainerInterface \$locator,
                ) {}

                public function __invoke(object \$message, \\Ultra\\MessageHandling\\MessageContext \$context): mixed
                {
            {$body}
                }
            }
            PHP;
    }
}
