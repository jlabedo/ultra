<?php

declare(strict_types=1);

namespace Ultra\MessageHandling_Compiler;

/**
 * Generates a compiled router PHP class from a resolved handler map.
 *
 * Parameterized by RouterDescriptor, which controls:
 *  - The router interface being implemented
 *  - Whether dispatch is single (one handler) or multi (N handlers)
 *  - The dispatch method name and first parameter name
 *  - The exception class to throw for unknown messages
 *
 * The generated class:
 *  - Implements the router interface
 *  - Has a ROUTES constant
 *  - Constructor: $locator, $messageContextPropagator
 *  - Public dispatch method: coerces context, creates dispatch context, routes, delegates
 *  - Private handler methods generated by HandlerMethodGenerator
 *
 * Contextual wrapper classes are generated separately into a shared file. Each wrapper
 * implements only the router interface, takes the inner router + parent context in its
 * constructor, and merges parent context before delegating. This replaces the previous
 * ContextAwareRouterInterface / withContext() approach and is decorator-safe.
 */
final class MessageRouterGenerator
{
    public function __construct(
        private readonly HandlerMethodGenerator $methodGenerator = new HandlerMethodGenerator(),
    ) {}

    /**
     * Generate the PHP source and write it to disk.
     *
     * The class name is derived from a content hash of the generated code:
     * the code is first built with a placeholder, hashed, and the placeholder
     * is replaced with the final name ({baseName}_{hash}). This ensures the
     * filename changes when the generated code changes (cache invalidation)
     * and stays stable when it doesn't.
     *
     * @param array<class-string, list<HandlerDescriptor>> $routes
     *
     * @return array{className: string, filePath: string}
     */
    public function generate(
        string $baseName,
        RouterDescriptor $descriptor,
        array $routes,
        string $outputDir,
        ?string $wrappersFilePath = null,
    ): array {
        $placeholder = '__ULTRA_COMPILED_CLASS__';
        $code = $this->buildCode($placeholder, $descriptor, $routes, $wrappersFilePath);

        $hash = substr(sha1($code), 0, 8);
        $className = $baseName . '_' . $hash;
        $code = str_replace($placeholder, $className, $code);

        $filePath = rtrim($outputDir, '/') . '/' . $className . '.php';
        $dir = dirname($filePath);
        if (! is_dir($dir)) {
            mkdir($dir, 0o777, true);
        }

        file_put_contents($filePath, $code);

        return ['className' => $className, 'filePath' => $filePath];
    }

    /**
     * Build the PHP source code string for a compiled router.
     *
     * @param array<class-string, list<HandlerDescriptor>> $routes
     */
    public function buildCode(
        string $className,
        RouterDescriptor $descriptor,
        array $routes,
        ?string $wrappersFilePath = null,
    ): string {
        $routeEntries = [];
        $handlerMethods = [];

        foreach ($routes as $messageClass => $handlers) {
            if ($descriptor->isSingleDispatch) {
                $handler = $handlers[0];
                $dispatchName = $this->singleDispatchMethodName($messageClass);
                $routeEntries[] = sprintf(
                    '        "%s" => %s,',
                    $messageClass,
                    var_export($dispatchName, true),
                );
                $handlerMethods[] = $this->methodGenerator->generate($dispatchName, $handler);
            } else {
                $invokeMethodNames = [];
                foreach ($handlers as $index => $handler) {
                    $invokeName = $this->multiDispatchMethodName($messageClass, $index);
                    $handlerMethods[] = $this->methodGenerator->generate($invokeName, $handler);
                    $invokeMethodNames[] = $invokeName;
                }
                $routeEntries[] = $this->buildMultiRouteEntry($messageClass, $invokeMethodNames);
            }
        }

        $routesCode = [] !== $routeEntries
            ? implode("\n", $routeEntries) . "\n"
            : '';
        $handlerMethodsCode = implode("\n\n", $handlerMethods);

        $interface = ltrim($descriptor->interfaceName, '\\');
        $dispatchMethod = $descriptor->isSingleDispatch
            ? $this->buildSingleDispatchMethod($descriptor)
            : $this->buildMultiDispatchMethod($descriptor);

        $requireLine = null !== $wrappersFilePath
            ? "\nrequire_once " . var_export($wrappersFilePath, true) . ";\n"
            : '';

        return <<<PHP
            <?php

            // This file is auto-generated by Ultra\\MessageHandling_Compiler\\MessageRouterCompilerPass. Do not edit manually.
            {$requireLine}
            final class {$className} implements \\{$interface}
            {
                private const ROUTES = [
            {$routesCode}    ];

                public function __construct(
                    private \\Psr\\Container\\ContainerInterface \$locator,
                    private \\Ultra\\MessageHandling\\MessageContextPropagatorInterface \$messageContextPropagator,
                ) {}

            {$dispatchMethod}

            {$handlerMethodsCode}
            }
            PHP;
    }

    /**
     * Build the PHP source for a contextual wrapper class.
     */
    public function buildWrapperCode(string $wrapperClassName, RouterDescriptor $descriptor): string
    {
        $interface = ltrim($descriptor->interfaceName, '\\');
        $method = $descriptor->methodName;
        $msgVar = '$' . $descriptor->firstParamName;
        $returnType = $descriptor->returnsVoid ? 'void' : 'mixed';
        $returnKeyword = $descriptor->returnsVoid ? '' : 'return ';

        return <<<PHP
            final readonly class {$wrapperClassName} implements \\{$interface}
            {
                public function __construct(
                    private \\{$interface} \$inner,
                    private \\Ultra\\MessageHandling\\MessageContext \$parentContext,
                ) {}

                public function {$method}(object {$msgVar}, array|\\Ultra\\MessageHandling\\MessageContext \$context = []): {$returnType}
                {
                    \$merged = \$this->parentContext->merge(\\Ultra\\MessageHandling\\MessageContext::coerce(\$context));
                    {$returnKeyword}\$this->inner->{$method}({$msgVar}, \$merged);
                }
            }
            PHP;
    }

    /**
     * Generate a shared file containing all contextual wrapper classes.
     *
     * @param array<string, RouterDescriptor> $wrapperClassToDescriptor Maps wrapper class name to its router descriptor
     */
    public function generateWrappersFile(array $wrapperClassToDescriptor, string $filePath): void
    {
        $dir = dirname($filePath);
        if (! is_dir($dir)) {
            mkdir($dir, 0o777, true);
        }

        file_put_contents($filePath, $this->buildWrappersFileCode($wrapperClassToDescriptor));
    }

    /**
     * Build the PHP source for the shared wrappers file. Exposed for testing.
     *
     * @param array<string, RouterDescriptor> $wrapperClassToDescriptor
     */
    public function buildWrappersFileCode(array $wrapperClassToDescriptor): string
    {
        $blocks = [];
        foreach ($wrapperClassToDescriptor as $wrapperClassName => $descriptor) {
            $blocks[] = $this->buildWrapperCode($wrapperClassName, $descriptor);
        }

        $wrappersCode = implode("\n\n", $blocks);

        return <<<PHP
            <?php

            // This file is auto-generated by Ultra\\MessageHandling_Compiler\\MessageRouterCompilerPass. Do not edit manually.

            {$wrappersCode}
            PHP;
    }

    /**
     * Compute the contextual wrapper class name from the router interface name.
     *
     * Uses a static hash (interface + outputDir) so the wrapper name is known
     * before code generation, independently of the compiled router's content hash.
     */
    public static function wrapperClassName(string $interfaceName, string $outputDir): string
    {
        $shortName = substr($interfaceName, strrpos($interfaceName, '\\') + 1);
        $hash = substr(sha1($interfaceName . $outputDir), 0, 8);

        return 'Contextual' . $shortName . '_' . $hash;
    }

    private function buildSingleDispatchMethod(RouterDescriptor $descriptor): string
    {
        $msgVar = '$' . $descriptor->firstParamName;
        $exceptionClass = ltrim($descriptor->noHandlerExceptionClass, '\\');

        $body = <<<PHP
                    \$messageContext = \$this->messageContextPropagator->createDispatchContext(\\Ultra\\MessageHandling\\MessageContext::coerce(\$context));
                    \$method = self::ROUTES[{$msgVar}::class] ?? null;
                    if (null === \$method) {
                        throw new \\{$exceptionClass}({$msgVar}::class);
                    }
                    return \$this->{\$method}({$msgVar}, \$messageContext);
            PHP;

        $method = $descriptor->methodName;

        return <<<PHP
                public function {$method}(object {$msgVar}, array|\\Ultra\\MessageHandling\\MessageContext \$context = []): mixed
                {
            {$body}
                }
            PHP;
    }

    private function buildMultiDispatchMethod(RouterDescriptor $descriptor): string
    {
        $msgVar = '$' . $descriptor->firstParamName;
        $exceptionClass = ltrim($descriptor->noHandlerExceptionClass, '\\');
        $method = $descriptor->methodName;

        $body = <<<PHP
                    \$messageContext = \$this->messageContextPropagator->createDispatchContext(\\Ultra\\MessageHandling\\MessageContext::coerce(\$context));
                    \$methods = self::ROUTES[{$msgVar}::class] ?? null;
                    if (null === \$methods) {
                        throw new \\{$exceptionClass}({$msgVar}::class);
                    }
                    foreach (\$methods as \$m) {
                        \$this->{\$m}({$msgVar}, \$messageContext);
                    }
            PHP;

        return <<<PHP
                public function {$method}(object {$msgVar}, array|\\Ultra\\MessageHandling\\MessageContext \$context = []): void
                {
            {$body}
                }
            PHP;
    }

    /**
     * @param list<string> $methodNames
     */
    private function buildMultiRouteEntry(string $messageClass, array $methodNames): string
    {
        if ([] === $methodNames) {
            return sprintf('        \%s::class => [],', ltrim($messageClass, '\\'));
        }

        $lines = [sprintf('        \%s::class => [', ltrim($messageClass, '\\'))];
        foreach ($methodNames as $methodName) {
            $lines[] = sprintf('            %s,', var_export($methodName, true));
        }
        $lines[] = '        ],';

        return implode("\n", $lines);
    }

    private function singleDispatchMethodName(string $messageClass): string
    {
        $short = substr($messageClass, strrpos($messageClass, '\\') + 1);
        $short = preg_replace('/[^A-Za-z0-9_]/', '', $short);

        return 'dispatch' . $short . '_' . substr(md5($messageClass), 0, 6);
    }

    private function multiDispatchMethodName(string $messageClass, int $index): string
    {
        $short = substr($messageClass, strrpos($messageClass, '\\') + 1);
        $short = preg_replace('/[^A-Za-z0-9_]/', '', $short);

        return 'invoke' . $short . '_' . $index . '_' . substr(md5($messageClass . '#' . $index), 0, 6);
    }
}
