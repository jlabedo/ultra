<?php

declare(strict_types=1);

namespace Ultra\EventSourcedState_Compiler;

use Ultra\CodeGeneration\PhpCode;
use Ultra\CodeGeneration\PhpFileWriter;

final class EventSourcedEntityLoaderGenerator
{
    public function __construct(
        private readonly PhpFileWriter $fileWriter = new PhpFileWriter(),
    ) {}

    public function generate(string $className, EventSourcedEntityDefinition $definition, string $filePath): void
    {
        $this->fileWriter->write($filePath, $this->buildCode($className, $definition));
    }

    public function buildCode(string $className, EventSourcedEntityDefinition $definition): string
    {
        $entityClassName = PhpCode::fqcn($definition->entityClass);
        $entityClassLiteral = PhpCode::classLiteral($definition->entityClass);
        $expectedTagsCode = PhpCode::exportStringList($definition->tags);
        $tagExtractionCode = $this->buildTagExtractionCode($definition);
        $queryCode = $this->buildQueryCode($definition);
        $dispatchCode = $this->buildDispatchCode($definition);

        return <<<PHP
            <?php

            // This file is auto-generated by Ultra\\EventSourcedState_Compiler\\EntityLoaderCompilerPass. Do not edit manually.

            final class {$className} implements \\Ultra\\EventSourcedState\\EventSourcedEntityLoader
            {
                public function __construct(
                    private \\Ultra\\Mapper\\UltraNormalizer \$normalizer,
                ) {}

                public function query(\\Ultra\\EventStore\\DomainIdentifier ...\$identifiers): \\Ultra\\EventStore\\StreamQuery
                {
                    \$tagValues = \\Ultra\\EventSourcedState\\EventSourcedTagValueResolver::resolve(
                        {$entityClassLiteral},
                        {$expectedTagsCode},
                        ...\$identifiers,
                    );

            {$tagExtractionCode}

                    return {$queryCode};
                }

                public function hydrate(array \$events, \\Ultra\\EventStore\\DomainIdentifier ...\$identifiers): {$entityClassName}
                {
                    \$query = \$this->query(...\$identifiers);
                    \$state = new \\{$definition->entityClass}();

                    foreach (\$events as \$event) {
                        if (! \$query->matches(\$event)) {
                            continue;
                        }

            {$dispatchCode}
                    }

                    return \$state;
                }
            }
            PHP;
    }

    private function buildTagExtractionCode(EventSourcedEntityDefinition $definition): string
    {
        $lines = [];

        foreach ($definition->tags as $tag) {
            $variableName = PhpCode::identifier($tag, 'tag');
            $tagLiteral = PhpCode::exportString($tag);
            $lines[] = sprintf('        $%s = $tagValues[%s];', $variableName, $tagLiteral);
        }

        return implode("\n", $lines);
    }

    private function buildQueryCode(EventSourcedEntityDefinition $definition): string
    {
        if ([] === $definition->criteriaGroups) {
            return '\Ultra\EventStore\StreamQuery::none()';
        }

        $branches = [];
        foreach ($definition->criteriaGroups as $group) {
            $identifiers = array_map(
                static fn (string $tag): string => isset($definition->aliases[$tag])
                    ? sprintf(
                        'new \Ultra\EventStore\DomainIdentifier(%s, $%s->value)',
                        PhpCode::exportString($tag),
                        PhpCode::identifier($definition->aliases[$tag], 'tag'),
                    )
                    : '$'.PhpCode::identifier($tag, 'tag'),
                $group->tags,
            );
            $branch = sprintf(
                '\Ultra\EventStore\StreamQuery::forStream(%s)->ofTypes(%s)',
                implode(', ', $identifiers),
                implode(', ', array_map(PhpCode::exportString(...), $group->eventNames)),
            );
            $branches[] = $branch;
        }

        if (1 === count($branches)) {
            return $branches[0];
        }

        return sprintf(
            '\Ultra\EventStore\StreamQuery::anyOf(%s)',
            implode(",\n            ", $branches),
        );
    }

    private function buildDispatchCode(EventSourcedEntityDefinition $definition): string
    {
        $cases = [];

        foreach ($definition->dispatchEntries as $entry) {
            $cases[] = sprintf(
                '                %s => $state->%s($this->normalizer->fromScalar($event->payload, \%s::class)),',
                PhpCode::exportString($entry->eventName),
                $entry->method,
                ltrim($entry->eventClass, '\\'),
            );
        }

        $defaultCase = sprintf(
            '                default => throw new \Ultra\EventSourcedState\Exception\UnhandledEventException($event->eventType, \%s::class),',
            ltrim($definition->entityClass, '\\'),
        );

        return "            match (\$event->eventType) {\n"
            .implode("\n", $cases)
            ."\n{$defaultCase}\n"
            .'            };';
    }
}
