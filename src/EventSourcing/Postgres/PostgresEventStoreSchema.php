<?php

declare(strict_types=1);

namespace Ultra\EventStore_Postgres;

use Ultra\EventStore_Postgres\LockStrategy\LockStrategy;
use Ultra\EventStore_Postgres\LockStrategy\SchemaLockStrategy;
use Ultra\Schema\ColumnDefinition;
use Ultra\Schema\ColumnType;
use Ultra\Schema\IndexDefinition;
use Ultra\Schema\PostgresSqlGenerator;
use Ultra\Schema\SchemaDefinition;
use Ultra\Schema\SchemaReconciler;
use Ultra\Schema\SqlType;
use Ultra\Schema\TableDefinition;

/** @internal Shared storage definitions for both PostgreSQL Event Store variants. */
final readonly class PostgresEventStoreSchema
{
    public const string DEFAULT_TABLE_PREFIX = 'event_store_';

    public function __construct(
        private string $tablePrefix,
        private LockStrategy $lockStrategy,
        private bool $hstore,
    ) {}

    public function definition(): SchemaDefinition
    {
        if (str_contains($this->tablePrefix, '.')) {
            throw new \InvalidArgumentException(
                'Event Store migrations require an unqualified table prefix. Select the PostgreSQL schema through search_path.',
            );
        }
        if (!$this->lockStrategy instanceof SchemaLockStrategy) {
            throw new \LogicException(sprintf(
                'Lock strategy "%s" must supply function definitions to generate Event Store migrations.',
                $this->lockStrategy->name(),
            ));
        }

        $storage = $this->storage();

        return new SchemaDefinition(
            $storage->tables,
            $storage->requiredExtensions,
            $this->lockStrategy->functionDefinitions($this->tablePrefix),
        );
    }

    /** @return list<string> */
    public function createStatements(): array
    {
        $operations = new SchemaReconciler()->reconcile(new SchemaDefinition([]), $this->storage());

        $statements = new PostgresSqlGenerator()->generate($operations);

        return [
            ...array_map(static fn(string $sql): string => rtrim($sql, ';'), $statements),
            ...$this->lockStrategy->createStatements($this->tablePrefix),
        ];
    }

    private function storage(): SchemaDefinition
    {
        $prefix = strtolower($this->tablePrefix);
        $events = $prefix . 'events';
        $indexes = [
            new IndexDefinition(
                'event_type_sequence',
                $events . '_event_type_sequence_idx',
                ['event_type', 'sequence'],
            ),
            new IndexDefinition('xid', $events . '_xid_idx', ['xid']),
        ];
        if ($this->hstore) {
            $indexes[] = new IndexDefinition(
                'event_type_domain_ids',
                $events . '_event_type_domain_ids_gin_idx',
                ['event_type', 'domain_ids'],
                method: 'gin',
            );
        }

        $tables = [new TableDefinition(
            'event_store.events',
            $events,
            columns: [
                new ColumnDefinition(
                    'sequence',
                    type: ColumnType::Int64,
                    constraints: ['GENERATED BY DEFAULT AS IDENTITY'],
                ),
                new ColumnDefinition('xid', type: SqlType::fromSql('xid8'), defaultExpression: 'pg_current_xact_id()'),
                new ColumnDefinition('event_type', type: ColumnType::Text),
                new ColumnDefinition('payload', type: ColumnType::Jsonb),
                new ColumnDefinition('metadata', type: ColumnType::Jsonb, defaultExpression: "'{}'::jsonb"),
                new ColumnDefinition('domain_ids', type: SqlType::fromSql($this->hstore ? 'hstore' : 'jsonb')),
                new ColumnDefinition(
                    'recorded_at',
                    type: ColumnType::TimestampWithTimeZone,
                    defaultExpression: 'statement_timestamp()',
                ),
            ],
            indexes: $indexes,
            primaryKey: ['sequence'],
        )];

        if ($this->hstore) {
            return new SchemaDefinition($tables, requiredExtensions: ['hstore', 'btree_gin']);
        }

        $identifiers = $prefix . 'event_domain_ids';
        $tables[] = new TableDefinition(
            'event_store.event_domain_ids',
            $identifiers,
            columns: [
                new ColumnDefinition('sequence', type: ColumnType::Int64),
                new ColumnDefinition('identifier_name', type: ColumnType::Text),
                new ColumnDefinition('identifier_value', type: ColumnType::Text),
                new ColumnDefinition('bucket', type: SqlType::fromSql('smallint')),
            ],
            indexes: [
                new IndexDefinition('sequence', $identifiers . '_sequence_idx', ['sequence']),
                new IndexDefinition('bucket', $identifiers . '_bucket_idx', ['bucket']),
            ],
            primaryKey: ['identifier_name', 'identifier_value', 'sequence'],
        );

        return new SchemaDefinition($tables);
    }
}
